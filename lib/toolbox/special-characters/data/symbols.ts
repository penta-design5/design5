import type { CharCategory, CharEntry } from '../types'

/**
 * 특수 문자 정적 데이터. 한 줄에 `문자 이름`(첫 공백 앞이 문자, 나머지가 한글 이름·별칭).
 * 칸당 1 grapheme이어야 하며(테스트로 검증) 이모지 표시 형태가 되는 문자(❤ ✔ 등 variation selector 필요)는 넣지 않는다.
 */
function parse(lines: string): CharEntry[] {
  return lines
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
    .map((l) => {
      const i = l.indexOf(' ')
      return { char: l.slice(0, i), name: l.slice(i + 1).trim() }
    })
}

